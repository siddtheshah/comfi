import { expect, test } from '@playwright/test'
import { Connection, PublicKey } from '@solana/web3.js'
import { getAccount } from '@solana/spl-token'
import { linkedUserAccounts, tokenAddress, walletMemberships } from '../src/pool-setup'
import { decodePoolAccountData } from '../src/solana'

// No wallet, pool, account, funding, signing, or RPC endpoints are mocked.
test('create a UserAccount, fund its selected wallet, deploy a pool, and reload confirmed membership', async ({ page }) => {
  const rpc = process.env.COMFI_POOL_TEST_RPC ?? 'http://127.0.0.1:18899'
  const connection = new Connection(rpc, 'confirmed'), program = new PublicKey('3vzvgpB5MWB2cHGPRzWtRmKeQtZVfkffu6uygjoNDDYP')
  await page.goto('/')
  await page.getByRole('button', { name: 'User account', exact: true }).click()
  await page.getByRole('button', { name: 'Use ComFi base wallet' }).click()
  const wallet = new PublicKey((await page.locator('.account-base code').innerText()).trim())
  const funding = await connection.requestAirdrop(wallet, 2_000_000_000)
  await expect.poll(async () => (await connection.getSignatureStatuses([funding])).value[0]?.confirmationStatus).toMatch(/confirmed|finalized/)
  await page.getByTestId('start-pool').click()
  await expect(page.getByText('No active UserAccount link was found for this wallet.')).toBeVisible()
  await page.getByRole('button', { name: 'Set up UserAccount', exact: true }).click()
  await page.getByLabel('Browser passcode', { exact: true }).fill('pool setup test passcode')
  await page.getByLabel('Confirm passcode', { exact: true }).fill('pool setup test passcode')
  await page.getByRole('button', { name: 'Create UserAccount', exact: true }).click()
  await expect(page.getByRole('status')).toContainText('UserAccount created and verified', { timeout: 30_000 })
  const user = await page.getByTestId('user-account-address').innerText()
  expect(await linkedUserAccounts(connection, wallet)).toEqual([user])
  await page.getByTestId('start-pool').click()
  await expect(page.getByLabel('UserAccount', { exact: true })).toHaveValue(user)
  await expect(page.getByTestId('pool-setup-wallet')).toHaveText(wallet.toBase58())
  await page.getByRole('button', { name: 'Approve and deploy pool' }).click()
  await expect(page.getByRole('alert')).toContainText('Fund the selected wallet')
  await page.getByRole('button', { name: 'Close pool setup' }).click()
  await page.getByRole('button', { name: '⚡ ComFi Wallet', exact: true }).click()
  await page.getByRole('button', { name: '💵 Mint 100 USDC', exact: true }).click()
  await expect(page.getByText(/Minted 100 test USDC to/)).toBeVisible({ timeout: 30_000 })
  await page.getByRole('button', { name: 'Done', exact: true }).click()
  await page.getByTestId('start-pool').click()
  await page.getByLabel('Contribution per cycle (USDC)', { exact: true }).fill('15')
  await page.getByLabel('Your initial deposit (USDC)', { exact: true }).fill('25')
  await page.getByLabel('Member capacity', { exact: true }).fill('36')
  await page.getByLabel('Cycle duration (days)', { exact: true }).fill('14')
  await page.getByLabel('Vote threshold (basis points)', { exact: true }).fill('6000')
  await page.screenshot({ path: '/tmp/comfi-pool-setup-desktop.png', fullPage: true })
  await page.setViewportSize({ width: 390, height: 844 })
  expect(await page.locator('.account-pool-setup').evaluate(el => el.scrollWidth <= el.clientWidth)).toBe(true)
  await page.screenshot({ path: '/tmp/comfi-pool-setup-mobile.png', fullPage: true })
  await page.setViewportSize({ width: 1280, height: 900 })
  await page.getByRole('button', { name: 'Approve and deploy pool' }).click()
  await expect(page.getByRole('status')).toContainText('Pool deployed and membership verified', { timeout: 30_000 })
  const accounts = await connection.getProgramAccounts(program, { filters: [{ memcmp: { offset: 0, bytes: 'hQrXeCntzbV' } }] })
  const pools = accounts.map(account => decodePoolAccountData(account.pubkey.toBase58(), account.account.data)).filter(pool => pool.creator === wallet.toBase58())
  expect(pools).toHaveLength(1)
  const pool = pools[0]
  expect(pool.memberCap).toBe(36); expect(pool.cycleDurationSeconds).toBe(14n * 86400n); expect(pool.voteThreshold).toBe(6000)
  const member = (await walletMemberships(connection, program, [pool.address], wallet)).get(pool.address)!
  expect(member.role).toBe('Admin'); expect(member.status).toBe('Active'); expect(member.depositedTotal).toBe(25_000_000n)
  const [global] = PublicKey.findProgramAddressSync([Buffer.from('global')], program)
  const config = await connection.getAccountInfo(global)
  const mint = new PublicKey(config!.data.subarray(40, 72))
  expect((await getAccount(connection, tokenAddress(wallet, mint))).amount).toBe(74_000_000n)
  expect((await getAccount(connection, new PublicKey(pool.vault))).amount).toBe(25_000_000n)
  await page.reload()
  // Select the same persisted browser wallet after reload.
  await page.getByRole('button', { name: 'User account', exact: true }).click()
  await page.getByRole('button', { name: 'Use ComFi base wallet' }).click()
  await page.getByRole('button', { name: 'My pools', exact: true }).first().click()
  await expect(page.getByTestId(`pool-pool-${pool.id}`)).toContainText('Admin · Active')
  expect(await page.evaluate(() => Object.keys(localStorage).filter(key => key.startsWith('comfi:pool-setup:v1:')))).toEqual([])
  await page.getByRole('button', { name: '⚡ ComFi Wallet', exact: true }).click()
  await page.getByRole('button', { name: /1-Click New Keypair/ }).click()
  await page.getByRole('button', { name: /Confirm Overwrite/ }).click()
  await page.getByRole('button', { name: 'Done', exact: true }).click()
  await expect(page.getByTestId(`pool-pool-${pool.id}`)).toContainText('No pool membership')
})
